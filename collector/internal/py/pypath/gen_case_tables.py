"""Writes case_tables.go: Python's str.casefold() and str.lower() for every code point they change.

Run with the reference interpreter (CPython 3.14.4, Unicode 16.0.0) from collector/:
    python3.14 internal/py/pypath/gen_case_tables.py
The table makes pypath independent of the Unicode version of Go's own case tables.
"""
import pathlib
import sys
import unicodedata

rows = []
for cp in range(0x110000):
    if 0xD800 <= cp <= 0xDFFF:
        continue
    c = chr(cp)
    fold, lower = c.casefold(), c.lower()
    if fold != c or lower != c:
        rows.append((cp, fold, lower))


def lit(s):
    return '"' + "".join("\\U%08x" % ord(ch) if ord(ch) > 0xFFFF else "\\u%04x" % ord(ch) for ch in s) + '"'


out = [
    "// Code generated by gen_case_tables.py from CPython %s (Unicode %s); DO NOT EDIT."
    % (sys.version.split()[0], unicodedata.unidata_version),
    "",
    "package pypath",
    "",
    'const caseTablesUnicode = "%s"' % unicodedata.unidata_version,
    "",
    "// caseTable lists, in code-point order, every code point that str.casefold() or str.lower()",
    "// changes, with both results.",
    "var caseTable = [...]caseEntry{",
]
out += ["\t{0x%04x, %s, %s}," % (cp, lit(f), lit(l)) for cp, f, l in rows]
out += ["}", ""]
pathlib.Path(__file__).with_name("case_tables.go").write_text("\n".join(out))
print(len(rows), "rows")
